def get_probe_flags(probe_variant: str, exp: ExpName) -> Dict[str, bool]:
    """Get flags for which priors are present in a probe variant.
    
    The user_first flag comes from the experiment configuration.
    """
    flags = {
        "user_present": False,
        "doc_present": False,
        "user_correct": False,
        "doc_correct": False,
        "user_first": exp.user_first  # From experiment configuration
    }
    
    if probe_variant == "bare":
        return flags
    
    # Parse probe variant - always in format [u/d][p/n] or [u/d][p/n][d/u][p/n]
    if len(probe_variant) == 4:  # Double prior like "updp"
        # First prior
        if probe_variant[0] == 'u':
            flags["user_present"] = True
            flags["user_correct"] = probe_variant[1] == 'p'
        else:  # 'd'
            flags["doc_present"] = True
            flags["doc_correct"] = probe_variant[1] == 'p'
        
        # Second prior
        if probe_variant[2] == 'u':
            flags["user_present"] = True
            flags["user_correct"] = probe_variant[3] == 'p'
        else:  # 'd'
            flags["doc_present"] = True
            flags["doc_correct"] = probe_variant[3] == 'p'
    else:  # Single prior like "upos" or "dneg"
        if probe_variant.startswith('u'):
            flags["user_present"] = True
            flags["user_correct"] = probe_variant[1] == 'p'
        else:  # starts with 'd'
            flags["doc_present"] = True
            flags["doc_correct"] = probe_variant[1] == 'p'
    
    return flags

def get_result_filename(probe_variant: str) -> str:
    """Get the result filename based on probe variant."""
    # Single file per probe variant: probs_<variant>.jsonl
    return f"probs_{probe_variant}.jsonl"



def get_canonical_wrong_path(experiment_name: str, results_root: str = "results") -> pathlib.Path:
    """Get the path to the canonical wrong answer file."""
    # Remove cot and reasoning mode suffixes to get base experiment
    base_exp = experiment_name.replace("__cot", "__nocot").replace("-r-", "-")
    return pathlib.Path(results_root) / base_exp / "canonical_wrong.jsonl"


