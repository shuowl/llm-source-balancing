    ap.add_argument("--results-root", default="results", help="Root directory for results")
    ap.add_argument("--experiment", help="Run only this specific experiment")
    ap.add_argument("--probe-variant", choices=ALL_PROBES, 
                    help="Run only this probe variant (default: run all)")
    ap.add_argument("--batch-size", type=int, default=8, 
                    help="Number of examples to process in each batch (default: 8)")
    ap.add_argument("--vllm-tp-size", type=int, default=1,
                    help="Tensor parallel size for vLLM (single replica sharded across N GPUs, default: 1)")
    ap.add_argument("--hf-gpus", type=str, default="all",
                    help="Number of GPUs for HF accelerate data parallelism (default: all, can be 1-N or 'all')")
    args = ap.parse_args()

    # Check GPU availability
    import torch
    available_gpus = torch.cuda.device_count() if torch.cuda.is_available() else 1

    # vLLM configuration (TP only)
    if args.vllm_tp_size > available_gpus:
        sys.exit(f"Error: --vllm-tp-size ({args.vllm_tp_size}) exceeds available GPUs ({available_gpus})")
    print(f"vLLM configuration: tensor_parallel_size={args.vllm_tp_size} (using {args.vllm_tp_size}/{available_gpus} GPUs)")

    # HF configuration (DP only via accelerate --num_processes)
    if args.hf_gpus == "all":
        hf_gpus = available_gpus
    else:
        try:
            hf_gpus = int(args.hf_gpus)
        except ValueError:
            sys.exit(f"Error: --hf-gpus must be a number or 'all'")
        if hf_gpus < 1 or hf_gpus > available_gpus:
            sys.exit(f"Error: --hf-gpus must be between 1 and {available_gpus}")
    print(f"HF configuration: {hf_gpus} GPUs via accelerate --num_processes")
    args.hf_gpus = hf_gpus
    
    # Load config
    cfg = yaml.safe_load(pathlib.Path(args.config).read_text())
    experiments = cfg.get("experiments", [])
    
    if not experiments:
        sys.exit("No experiments found in config.")
    
    # Filter experiments if requested
    if args.experiment:
        experiments = [e for e in experiments if e["name"] == args.experiment]
        if not experiments:
            sys.exit(f"Experiment '{args.experiment}' not found in config.")
    
    # Prepare datasets manifest
    manifest_path = ROOT / "data" / "prepared_datasets.yaml"
    if not manifest_path.exists():
        sys.exit("prepared_datasets.yaml missing – run data/prepare_datasets.py first.")
    manifest = yaml.safe_load(manifest_path.read_text())
    
    # Run experiments
    for exp_config in experiments:
        name = exp_config["name"]
        exp = parse_experiment_name(name)
        
        # Get test file
        dataset_ref = f"{exp.dataset}_default_split"
        eval_jsonl = manifest[dataset_ref]["test_file"]
        
        print(f"\n{'='*60}")
        print(f"Experiment: {name}")
        print(f"Dataset: {exp.dataset}")
        print(f"Model: {exp.hf_model_id}")
        print(f"{'='*60}")
        
