#!/usr/bin/env python3
"""
run_experiments.py - Main orchestrator for running probe experiments.

This script coordinates the execution of various probe variants for experiments
defined in YAML configuration files. Each probe generates both model outputs and
probability distributions in a single pass.

EXECUTION FLOW:
---------------
1. Run bare probe first (required for canonical wrong answers)
   - Delegates to run_single_probe.py
   - Processes with configurable batch_size (default: 8)
   - Does NOT require tier sentences or canonical wrong answers
   
2. Create canonical_wrong.jsonl from bare results (for base experiments)
   - Generated after bare probe completes
   - Contains the "canonical wrong" answer for each question
   
3. Batch process all non-bare probes using unified computation
   - Uses run_batch_probes_efficient.py for maximum efficiency
   - Loads model only ONCE and processes all variants together
   - Requires tier sentences (if using Tier 2) and canonical_wrong.jsonl
   - Also uses configurable batch_size (default: 8)

PROBE VARIANTS (9 per experiment):
----------------------------------
Each experiment runs 9 probe variants total, consisting of:

1. Single-prior variants (5):
   - bare: No priors (baseline) - ALWAYS RUN FIRST
   - upos: User statement supporting correct answer
   - uneg: User statement supporting wrong answer  
   - dpos: Document supporting correct answer
   - dneg: Document supporting wrong answer

2. Double-prior variants (4, based on experiment's prior order):
   - For user-first experiments (e.g., undn):
     - updp: User positive + Document positive
     - updn: User positive + Document negative
     - undp: User negative + Document positive
     - undn: User negative + Document negative
   
   - For doc-first experiments (e.g., dnun):
     - dpup: Document positive + User positive
     - dpun: Document positive + User negative
     - dnup: Document negative + User positive
     - dnun: Document negative + User negative

MULTI-GPU ACCELERATION:
-----------------------
HF Probing (controlled by --hf-gpus parameter):
- Default: all GPUs (can specify 1-8 or "all" for all available GPUs)
- Uses `accelerate launch --num_processes N` for data parallelism:
  splits evaluation data across N GPUs, each processes 1/N of the dataset.

vLLM Generation (for reasoning models):
- Controlled by --vllm-tp-size parameter.
- Single model replica, optionally sharded across N GPUs via
  vLLM's native tensor_parallel_size.

OUTPUT FILES:
-------------
Files are saved in results/<experiment_name>/ with naming convention:
- probs_<variant>.jsonl: Unified results with both outputs and probabilities
- canonical_wrong.jsonl: Most probable wrong answers (created after bare probe)

USAGE EXAMPLES:
---------------
# Run all probe variants with default settings (all GPUs for HF data parallelism)
python experiments/run_experiments.py --config experiments/generated/exp1_config.yaml

# Run with larger batch size for HF probing
python experiments/run_experiments.py --config experiments/generated/exp1_config.yaml --batch-size 32

# Run on 4 GPUs (HF accelerate data parallel across 4 GPUs)
python experiments/run_experiments.py --config experiments/generated/exp1_config.yaml --hf-gpus 4

# Run with vLLM TP-sharding the reasoning model across 2 GPUs
python experiments/run_experiments.py --config experiments/generated/exp1_config.yaml --vllm-tp-size 2

# Run a specific probe variant
python experiments/run_experiments.py --config experiments/generated/exp1_config.yaml --probe-variant upos --hf-gpus 4

# Run one specific experiment from the config
python experiments/run_experiments.py --config experiments/generated/exp1_config.yaml --experiment csqa__qwen3_1_7b__dnunin__nocot --hf-gpus 8

# GPU ALLOCATION NOTES:
# - vLLM: --vllm-tp-size N shards a single replica across N GPUs (native vLLM TP).
# - HF:   --hf-gpus N launches N accelerate processes (data parallelism).

RESULT FILE FORMAT:
-------------------
Unified probe files (probs_<variant>.jsonl) contain JSONL with fields:
- qid: Question ID
- probe_variant: Which probe variant was used
- gold: Correct answer letter (e.g., "A", "B", "C")
- output_letter: Model's predicted answer letter
- raw_output: Raw text generated by the model
- probs: List of probability objects, each containing:
  - letter: Answer choice letter (e.g., "A", "B", "C")
  - text: The answer choice text
  - prob: Probability of this choice (0-1)
  - logp: Log probability of this choice
- choices: List of answer choice texts
- pure_prompt: The prompt without chat formatting
- system_prompt: System prompt used

Canonical wrong file (canonical_wrong.jsonl) contains JSONL with fields:
- qid: Question ID
- gold: Correct answer letter
- gold_text: Text of the correct answer
- canonical_wrong: Most probable wrong answer letter
- canonical_wrong_text: Text of the canonical wrong answer

"""

