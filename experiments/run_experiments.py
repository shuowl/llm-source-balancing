def setup_logging(experiment_name: str, results_root: str = "results") -> logging.Logger:
    """Set up logging for experiment execution tracking.
    
    Args:
        experiment_name: Name of the experiment
        results_root: Root directory for results
        
    Returns:
        Logger instance configured for this experiment
    """
    # Create logs directory
    log_dir = pathlib.Path(results_root) / experiment_name / "logs"
    log_dir.mkdir(parents=True, exist_ok=True)
    
    # Create log file with timestamp
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    log_file = log_dir / f"execution_{timestamp}.log"
    
    # Configure logger
    logger = logging.getLogger(f"experiment_{experiment_name}")
    logger.setLevel(logging.DEBUG)
    
    # Remove existing handlers to avoid duplicates
    logger.handlers.clear()
    
    # File handler for detailed logs
    file_handler = logging.FileHandler(log_file)
    file_handler.setLevel(logging.DEBUG)
    
    # Console handler for important messages
    console_handler = logging.StreamHandler()
    console_handler.setLevel(logging.INFO)
    
    # Simple format - just the message, no prefixes
    simple_formatter = logging.Formatter('%(message)s')
    file_handler.setFormatter(simple_formatter)
    console_handler.setFormatter(simple_formatter)
    
    logger.addHandler(file_handler)
    logger.addHandler(console_handler)
    
    return logger


def validate_file_lines(file_path: pathlib.Path, expected_lines: int) -> bool:
    """Validate that a file exists and has the expected number of lines."""
    if not file_path.exists():
        return False
    
    try:
        with open(file_path) as f:
            line_count = sum(1 for _ in f)
        return line_count == expected_lines
    except Exception:
        return False


def check_all_files_complete(experiment_name: str, eval_jsonl: str, results_root: str = "results") -> bool:
    """Check if all required files exist with correct line counts.
    
    For normal models: 11 files (9 probs_*.jsonl + canonical_wrong.jsonl + merged_results.jsonl)
    For reasoning models: 20 files (above 11 + 9 *_vllm_reasoning.jsonl)
    
    Returns True only if ALL files are present and have the correct number of lines.
    """
    res_dir = pathlib.Path(results_root) / experiment_name
    
    # Get expected line count from test data
    expected_lines = 0
    with open(eval_jsonl) as f:
        expected_lines = sum(1 for _ in f)
    
    if expected_lines == 0:
        return False
    
    # Parse experiment to determine probe variants
    exp = parse_experiment_name(experiment_name)
    
    # Check canonical_wrong.jsonl
    if not validate_file_lines(res_dir / "canonical_wrong.jsonl", expected_lines):
        return False
    
    # Check merged_results.jsonl (should have 9 * expected_lines)
    if not validate_file_lines(res_dir / "merged_results.jsonl", 9 * expected_lines):
        return False
    
    # Determine probe variants based on experiment order
    probe_variants = ["bare", "upos", "uneg", "dpos", "dneg"]
    if exp.user_first:
        probe_variants.extend(["updp", "updn", "undp", "undn"])
    else:
        probe_variants.extend(["dpup", "dpun", "dnup", "dnun"])
    
    # Check all 9 probe variant files
    for pv in probe_variants:
        if not validate_file_lines(res_dir / f"probs_{pv}.jsonl", expected_lines):
            return False
    
    # For reasoning models, also check vLLM reasoning files
    if exp.reasoning_mode:
        for pv in probe_variants:
            vllm_file = res_dir / f"{pv}_vllm_reasoning.jsonl"
            if not validate_file_lines(vllm_file, expected_lines):
                return False
    
    return True


def run_experiments(experiment_name: str, eval_jsonl: str,
                   results_root: str = "results", probe_variant: str = None,
                   config_path: str = None, batch_size: int = 8,
                   vllm_tp_size: int = 1, hf_gpus: int = 1) -> None:
    """Run probe variant(s) for the experiment.

    Args:
        experiment_name: Name of the experiment
        eval_jsonl: Path to evaluation data
        results_root: Root directory for results
        probe_variant: Specific probe variant to run (None = run all)
        config_path: Path to config file (for error messages)
        batch_size: Number of examples to process in each batch (default: 8)
        vllm_tp_size: Tensor parallel size for vLLM (single replica sharded across N GPUs)
        hf_gpus: Number of GPUs for HF accelerate (data parallel, via --num_processes)
    """
    
    # Check if all files are already complete (only when running all probes)
    if probe_variant is None and check_all_files_complete(experiment_name, eval_jsonl, results_root):
        exp = parse_experiment_name(experiment_name)
        file_count = 20 if exp.reasoning_mode else 11
        print(f"\n✓ All {file_count} files already exist with correct line counts for {experiment_name}")
        if exp.reasoning_mode:
            print(f"  (11 result files + 9 vLLM reasoning files)")
        print(f"  Skipping experiment.")
        return
    
    exp = parse_experiment_name(experiment_name)
    res_dir = pathlib.Path(results_root) / experiment_name
    res_dir.mkdir(parents=True, exist_ok=True)
    
    # Set up logging
    logger = setup_logging(experiment_name, results_root)
    start_time = datetime.now()
    logger.info("="*80)
    logger.info(f"EXPERIMENT START: {start_time.strftime('%Y-%m-%d %H:%M:%S')}")
    logger.info(f"Starting experiment: {experiment_name}")
    logger.info(f"Probe variant: {probe_variant if probe_variant else 'all'}")
    logger.info(f"Experiment details:")
    logger.info(f"  - Dataset: {exp.dataset}")
    logger.info(f"  - Model: {exp.hf_model_id}")
    logger.info(f"  - Reasoning mode: {exp.reasoning_mode}")
    logger.info(f"  - CoT mode: {exp.use_cot}")
    logger.info(f"  - User tier: {exp.user_tier}")
    logger.info(f"  - Doc tier: {exp.doc_tier}")
    logger.info(f"  - User strength: {exp.user_strength}")
    logger.info(f"  - Doc strength: {exp.doc_strength}")
    logger.info(f"  - User first: {exp.user_first}")
    logger.info(f"  - Instruction: {exp.instruction}")
    logger.info("="*80)
    
    # Determine base experiment name for canonical wrong copying
    # Always need: non-reasoning + nocot + tier1 version
    
    base_exp = None
    copy_reason = None
    possible_base_exps = []  # For error messages
    
    # NEW: Track experiments that can provide specific probe files
    user_probe_source = None  # Experiment to copy upos/uneg from
    doc_probe_source = None   # Experiment to copy dpos/dneg from
    
    # Check if we should look for other tier variants to copy from
    # Only check tier variants if we might need to copy canonical_wrong.jsonl
    # This is only relevant when running bare probe or all probes
    should_check_tier_variants = probe_variant is None or probe_variant == "bare"
    
    if should_check_tier_variants:
        logger.info("\nChecking for existing tier variants...")
    
    if should_check_tier_variants:
        # Build all possible tier variant names (except current one)
        parts = experiment_name.split("__")
        if len(parts) == 4:
            dataset, model, prior_instr, cot = parts
            
            # Extract instruction part (after 'i')
            i_pos = prior_instr.rfind('i')
            instruction = prior_instr[i_pos:]
            
            # Build all 8 combinations (4 tier combinations × 2 orders)
            # Since bare probe doesn't care about order, we check both orders
            tier_combinations = [(1, 1), (1, 2), (2, 1), (2, 2)]
            
            # Check all other tier/order combinations (not including current)
            possible_base_exps = []
            for user_t, doc_t in tier_combinations:
                for user_first_variant in [True, False]:
                    # Skip if this is the current experiment
                    if (user_t, doc_t) == (exp.user_tier, exp.doc_tier) and user_first_variant == exp.user_first:
                        continue
                    
                    # Build experiment name with this tier/order combination
                    if user_first_variant:
                        new_prior = f"u{user_t}{exp.user_strength[0]}d{doc_t}{exp.doc_strength[0]}{instruction}"
                    else:
                        new_prior = f"d{doc_t}{exp.doc_strength[0]}u{user_t}{exp.user_strength[0]}{instruction}"
                    
                    exp_name = f"{dataset}__{model}__{new_prior}__{cot}"
                    order_str = "user-first" if user_first_variant else "doc-first"
                    possible_base_exps.append((exp_name, user_t, doc_t, order_str))
            
            logger.info(f"\nChecking {len(possible_base_exps)} tier/order variants for existing results...")
            
            # Find first existing experiment with BOTH canonical_wrong.jsonl and probs_bare.jsonl
            base_exp = None
            for exp_name, user_t, doc_t, order_str in possible_base_exps:
                canonical_path_check = pathlib.Path(results_root) / exp_name / "canonical_wrong.jsonl"
                bare_path_check = pathlib.Path(results_root) / exp_name / "probs_bare.jsonl"
                if canonical_path_check.exists() and bare_path_check.exists():
                    base_exp = exp_name
                    copy_reason = f"tier/order variation (copying from tier {user_t}/{doc_t}, {order_str})"
                    logger.info(f"✓ Found: {exp_name} (both canonical_wrong.jsonl and probs_bare.jsonl exist)")
                    break
                elif canonical_path_check.exists() or bare_path_check.exists():
                    # One file exists but not both - this is an error condition
                    missing_file = "probs_bare.jsonl" if canonical_path_check.exists() else "canonical_wrong.jsonl"
                    error_msg = f"\nERROR: Incomplete tier variant found!\n"
                    error_msg += f"  Experiment: {exp_name}\n"
                    error_msg += f"  Has: {canonical_path_check.name if canonical_path_check.exists() else bare_path_check.name}\n"
                    error_msg += f"  Missing: {missing_file}\n"
                    error_msg += f"\nBoth canonical_wrong.jsonl and probs_bare.jsonl must exist for copying.\n"
                    error_msg += f"Please complete the experiment or remove the partial files."
                    raise FileNotFoundError(error_msg)
            
            if not base_exp:
                logger.info("No existing tier variants found")
                copy_reason = f"tier {exp.user_tier}/{exp.doc_tier} variation"
            
            # NEW: Also search for experiments that match specific tiers
            # This allows copying upos/uneg from one experiment and dpos/dneg from another
            logger.info("\nSearching for tier-specific probe sources...")
            
            for exp_name, user_t, doc_t, order_str in possible_base_exps:
                exp_dir = pathlib.Path(results_root) / exp_name
                
                # Check if this experiment has matching user tier and upos/uneg files
                if user_t == exp.user_tier and not user_probe_source:
                    upos_path = exp_dir / "probs_upos.jsonl"
                    uneg_path = exp_dir / "probs_uneg.jsonl"
                    if upos_path.exists() and uneg_path.exists():
                        user_probe_source = exp_name
                        logger.info(f"✓ Found user probe source: {exp_name} (tier u{user_t}n)")
                
                # Check if this experiment has matching doc tier and dpos/dneg files
                if doc_t == exp.doc_tier and not doc_probe_source:
                    dpos_path = exp_dir / "probs_dpos.jsonl"
                    dneg_path = exp_dir / "probs_dneg.jsonl"
                    if dpos_path.exists() and dneg_path.exists():
                        doc_probe_source = exp_name
                        logger.info(f"✓ Found doc probe source: {exp_name} (tier d{doc_t}n)")
                
                # Stop if we found both sources
                if user_probe_source and doc_probe_source:
                    break
    else:
        logger.info("\nSkipping tier variant check (running specific non-bare probe)")
    
    # Determine which probes to run
    logger.info("\nDetermining probe variants to run...")
    if probe_variant:
        probes_to_run = [probe_variant]
        logger.info(f"  - Running specific probe: {probe_variant}")
    else:
        # Filter probes based on experiment's prior order
        # Always include single-prior probes
        probes_to_run = ["bare", "upos", "uneg", "dpos", "dneg"]
        
        # Add appropriate double-prior probes based on experiment's prior order
        if exp.user_first:
            # User-first experiments use updp, updn, undp, undn
            probes_to_run.extend(["updp", "updn", "undp", "undn"])
            logger.info(f"  - User-first experiment: including updp, updn, undp, undn")
        else:
            # Doc-first experiments use dpup, dpun, dnup, dnun
            probes_to_run.extend(["dpup", "dpun", "dnup", "dnun"])
            logger.info(f"  - Doc-first experiment: including dpup, dpun, dnup, dnun")
        
        logger.info(f"  - Total probes to run: {len(probes_to_run)}")
    
    # Determine which probes need to be run
    probes_to_generate = []
    for pv in probes_to_run:
        output_file = res_dir / get_result_filename(pv)
        if not output_file.exists():
            probes_to_generate.append(pv)
    
    # Simple summary
    if probes_to_generate:
        logger.info(f"\nProbes to generate: {', '.join(probes_to_generate)}")
    else:
        logger.info(f"\nAll probe files already exist")
    
    # Summary of what we're doing
    if probe_variant:
        logger.info(f"\nRunning single probe: {probe_variant}")
    else:
        logger.info(f"\nRunning {len(probes_to_run)} probes: {', '.join(probes_to_run)}")
    
    # Track all output files
    output_files = []
    
    # Check if canonical wrong file exists
    canonical_path = res_dir / "canonical_wrong.jsonl"
    
    if base_exp and base_exp != experiment_name and not canonical_path.exists():
        base_canonical_path = pathlib.Path(results_root) / base_exp / "canonical_wrong.jsonl"
        found_path = base_canonical_path
        found_exp = base_exp
        
        if found_path:
            import shutil
            shutil.copy2(found_path, canonical_path)
            logger.info(f"\n✓ Copied canonical_wrong.jsonl from: {base_exp}")
            
            # Copy bare probe file (bare doesn't use tier sentences, so it's the same)
            bare_src = found_path.parent / "probs_bare.jsonl"
            bare_dst = res_dir / "probs_bare.jsonl"
            
            # We already verified bare_src exists in the search loop above
            if not bare_dst.exists():
                shutil.copy2(bare_src, bare_dst)
                logger.info(f"✓ Copied probs_bare.jsonl from: {base_exp}")
                output_files.append(("bare", str(bare_dst)))
            
            # Copy probe files that don't depend on the changed tier
            # Parse base experiment to check which tiers differ
            base_exp_parsed = parse_experiment_name(base_exp)
            
            # Determine which probes can be copied based on tier differences
            probes_to_copy = []
            
            # If user tier is same (u1n → u1n or u2n → u2n), copy user probes
            if exp.user_tier == base_exp_parsed.user_tier:
                probes_to_copy.extend(["upos", "uneg"])
                logger.info(f"  User tier unchanged (u{exp.user_tier}n) - will copy upos, uneg")
            
            # If doc tier is same (d1n → d1n or d2n → d2n), copy doc probes  
            if exp.doc_tier == base_exp_parsed.doc_tier:
                probes_to_copy.extend(["dpos", "dneg"])
                logger.info(f"  Doc tier unchanged (d{exp.doc_tier}n) - will copy dpos, dneg")
            
            # Copy the probe files that don't depend on changed tiers
            for pv in probes_to_copy:
                src_file = found_path.parent / f"probs_{pv}.jsonl"
                dst_file = res_dir / f"probs_{pv}.jsonl"
                if src_file.exists() and not dst_file.exists():
                    shutil.copy2(src_file, dst_file)
                    logger.info(f"✓ Copied probs_{pv}.jsonl from: {base_exp}")
                    output_files.append((pv, str(dst_file)))
                    
                    # Remove from probes_to_generate if it was there
                    if pv in probes_to_generate:
                        probes_to_generate.remove(pv)
            
            # Note: Double-prior probes (updp, updn, etc.) always need recomputation 
            # as they depend on both tiers
        else:
            # This is an error condition - we need the base canonical wrong file
            if possible_base_exps:
                error_msg = f"\nERROR: No tier/order variant has been run yet!\n"
                error_msg += f"  Current experiment: {experiment_name} (tier {exp.user_tier}/{exp.doc_tier}, {'user-first' if exp.user_first else 'doc-first'})\n"
                error_msg += f"  Checked tier/order combinations:\n"
                for exp_name, user_t, doc_t, order_str in possible_base_exps:
                    error_msg += f"    - {exp_name} (tier {user_t}/{doc_t}, {order_str}) - not found\n"
                error_msg += f"\nPlease run any one of these experiments first:\n"
                if config_path:
                    for exp_name, _, _, _ in possible_base_exps[:2]:  # Show first 2 as examples
                        error_msg += f"  python experiments/run_experiments.py --config {config_path} --experiment {exp_name}\n"
                else:
                    error_msg += f"  python experiments/run_experiments.py --config <config_file> --experiment <any_tier_variant>"
            else:
                error_msg = f"\nERROR: Cannot find canonical_wrong.jsonl!\n"
                error_msg += f"  Current experiment: {experiment_name}\n"
                error_msg += f"  This should not happen for base experiments.\n"
            raise FileNotFoundError(error_msg)
    
    if canonical_path.exists() and probe_variant != "bare":
        logger.info(f"\n✓ Found canonical_wrong.jsonl")
    
    # NEW: Copy single-prior probes from tier-specific sources
    # This happens AFTER the base_exp copying, to handle cases where
    # we need to copy from multiple different experiments
    if not probe_variant:  # Only when running all probes
        import shutil
        
        # Copy user probes from user_probe_source if available
        if user_probe_source and user_probe_source != experiment_name:
            user_source_dir = pathlib.Path(results_root) / user_probe_source
            for pv in ["upos", "uneg"]:
                if pv in probes_to_generate:
                    src_file = user_source_dir / f"probs_{pv}.jsonl"
                    dst_file = res_dir / f"probs_{pv}.jsonl"
                    if src_file.exists() and not dst_file.exists():
                        shutil.copy2(src_file, dst_file)
                        logger.info(f"✓ Copied probs_{pv}.jsonl from: {user_probe_source}")
                        output_files.append((pv, str(dst_file)))
                        probes_to_generate.remove(pv)
        
        # Copy doc probes from doc_probe_source if available
        if doc_probe_source and doc_probe_source != experiment_name:
            doc_source_dir = pathlib.Path(results_root) / doc_probe_source
            for pv in ["dpos", "dneg"]:
                if pv in probes_to_generate:
                    src_file = doc_source_dir / f"probs_{pv}.jsonl"
                    dst_file = res_dir / f"probs_{pv}.jsonl"
                    if src_file.exists() and not dst_file.exists():
                        shutil.copy2(src_file, dst_file)
                        logger.info(f"✓ Copied probs_{pv}.jsonl from: {doc_probe_source}")
                        output_files.append((pv, str(dst_file)))
                        probes_to_generate.remove(pv)
    
    if not probes_to_generate:
        logger.info("\nAll requested files already exist. Nothing to do.")
        return
    
    # Separate bare probe from non-bare probes
    bare_probes = [pv for pv in probes_to_generate if pv == "bare"]
    non_bare_probes = [pv for pv in probes_to_generate if pv != "bare"]
    
    # If we copied files from another tier variant, remove them from generation list
    if base_exp and canonical_path.exists():
        # Check which files were already copied and remove from generation lists
        for pv in list(bare_probes):
            if (res_dir / f"probs_{pv}.jsonl").exists():
                bare_probes.remove(pv)
        
        for pv in list(non_bare_probes):
            if (res_dir / f"probs_{pv}.jsonl").exists():
                non_bare_probes.remove(pv)
    
    # Run bare probe first if needed
    if bare_probes:
        logger.info(f"\n✓ Generating bare probe...")
        for pv in bare_probes:
            output_path = run_single_probe_via_script(experiment_name, pv, eval_jsonl,
                                                     results_root, batch_size,
                                                     vllm_tp_size, hf_gpus)
            output_files.append((pv, output_path))
            
        # Always create canonical wrong file after running bare probe
        # (unless it already exists)
        canonical_path = pathlib.Path(results_root) / experiment_name / "canonical_wrong.jsonl"
        if not canonical_path.exists():
            bare_file = pathlib.Path(results_root) / experiment_name / "probs_bare.jsonl"
            if bare_file.exists():
                create_canonical_wrong_file(experiment_name, results_root)
                logger.info("✓ Created canonical_wrong.jsonl")
            else:
                logger.warning("Cannot create canonical wrong file - missing bare file")
    
    # Run non-bare probes in batch if there are any
    if non_bare_probes:
        logger.info(f"\n✓ Generating {len(non_bare_probes)} non-bare probes in batch mode...")
        
        # Import here to avoid circular imports
        sys.path.append(str(ROOT / "experiments"))
        from run_batch_probes_efficient import run_batch_probes_efficient
        run_batch_probes_efficient(experiment_name, non_bare_probes, eval_jsonl,
                                 results_root, batch_size, vllm_tp_size, hf_gpus)
        
        # Add to output files
        for pv in non_bare_probes:
            output_path = pathlib.Path(results_root) / experiment_name / get_result_filename(pv)
            output_files.append((pv, str(output_path)))
    
    end_time = datetime.now()
    duration = end_time - start_time
